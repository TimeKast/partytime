#!/usr/bin/env node
/**
 * Project the repo's Claude Code instructions onto the instruction files that the OTHER
 * coding agents read: Codex, Cursor, GitHub Copilot and Hermes.
 *
 * PRINCIPLE: "what Claude Code sees is what Codex sees" — minus what is runtime-specific
 * and minus what is internal to the project. The four outputs are GENERATED, never
 * hand-edited: a single source (`CLAUDE.md` + the kit rules) cannot drift against itself.
 *
 * Usage:
 *   node scripts/tools/generate-agent-adapters.mjs           # rewrite the four adapters
 *   node scripts/tools/generate-agent-adapters.mjs --check   # exit 1 on drift, never writes
 *
 * ── THE GRAPH IS BOUNDED, NOT "everything CLAUDE.md imports" ────────────────────────────
 *
 *  1. Start at `CLAUDE.md` (its own prose) and walk its `@path` imports.
 *  2. A `@path` resolves RELATIVE TO THE FILE THAT CONTAINS IT (Claude Code memory docs),
 *     so `@CORE.md` inside `.claude/rules/INDEX.md` is `.claude/rules/CORE.md`. The
 *     boundary below is applied to the RESOLVED, repo-relative path — never to the raw
 *     spec, which says nothing about where the file actually lives. (Claude Code follows
 *     4 levels of `@import`; the `CLAUDE.md → INDEX.md → rule` chain spends 2 of them, so
 *     a rule that imports another one still resolves. This walk has no depth limit of its
 *     own — the graph it reads is the one the runtime already bounded.)
 *  3. BOUNDARY: only files under `.claude/rules/` are projected. `@project/planning/
 *     project-config.md` is a real import of `CLAUDE.md` and stays OUT: it carries infra,
 *     env var names and the project's business rules, and `.github/copilot-instructions.md`
 *     is visible to every collaborator with Copilot enabled. The same budget argument that
 *     excludes `CC.md` applies — Copilot and Cursor have small instruction budgets.
 *  4. `CC.md` is excluded BY NAME, not by heuristic. It is 100% Claude Code runtime (Agent
 *     tool, skill announcing, settings.json, Plan Mode): noise elsewhere at best, impossible
 *     instructions at worst. The generator does not try to "detect" non-portable content.
 *  5. `INDEX.md` is TRAVERSED but its own body is NOT emitted. It is the spine of the graph,
 *     not doctrine: its content is the import list itself (dropped from every body) plus an
 *     HTML comment about `@import` mechanics, which means nothing to another runtime. It is
 *     also OPTIONAL: the `core` profile ships no INDEX and wires the rules with explicit
 *     `@.claude/rules/*.md` lines in `CLAUDE.md`, and that graph projects exactly the same.
 *  6. A rule the dev adds under `.claude/rules/` — a `@.claude/rules/MI-REGLA.md` in
 *     CLAUDE.md, or an extra line in the INDEX — IS projected. The boundary is a location,
 *     not an allowlist of the kit's six files. A file reached through two paths is emitted
 *     once (dedup by repo-relative path).
 *
 * ── THE TWO CONTRACTS OF THE MOULD (`generate-skin-import.mjs`), COPIED AS TWO ──────────
 *
 *  · TOLERANT about an uninitialized system (`skipUnsplit` there, `skipUninitialized` here):
 *    no `CLAUDE.md`, a rule the graph references that is not on disk, or a `CLAUDE.md` that
 *    reaches NO rule under `.claude/rules/` at all → clean no-op, exit 0, with the reason
 *    printed. `.husky/pre-commit` states that "a missing alias must never abort commits
 *    (stale autogen is acceptable degradation; a blocked repo is not)".
 *    🔴 The precondition is what the graph RESOLVES TO, never "is `INDEX.md` installed":
 *    a `core` derivative has no INDEX and still has a perfectly projectable graph, and a
 *    `CLAUDE.md` that imports an INDEX which is not on disk is already covered by the
 *    missing-file branch of the walk. Requiring the INDEX would silently skip every `core`
 *    repo — the majority of the non-Next fleet.
 *  · FAIL-CLOSED about real drift: when the graph resolves completely and an output does not
 *    match what the generator would produce, `--check` exits 1 with a diff and writes
 *    nothing. A real write failure also exits non-zero — and never leaves a half-written
 *    output, because every write goes to a temp file and is renamed into place.
 *
 * ── THE IN-FILE "GENERATED" MARKER ──────────────────────────────────────────────────────
 *
 * Each output opens with `@generated by scripts/tools/generate-agent-adapters.mjs`. That
 * marker — not a delimited block inside the file — is the ownership unit here, because
 * unlike `globals.css` (where the kit owns ONE line of a file the app owns) these four
 * files are generated whole. PROJ-004 reads it as its ownership guard: an adapter WITHOUT
 * the marker is the derivative's own file and must be left alone. `hasGeneratedMarker()` is
 * exported for that reuse, which is why this script guards its CLI entry point with
 * `isMainModule` instead of running on import.
 *
 * `.cursor/rules/timekast.mdc` carries Cursor's YAML frontmatter (`description`,
 * `alwaysApply`), so its marker goes in an HTML comment IMMEDIATELY AFTER the frontmatter,
 * not as a frontmatter field: Cursor's documented MDC fields are a closed set, and an
 * unknown key there is a silent no-op at best. `hasGeneratedMarker` therefore scans the
 * first lines of the file rather than requiring line 1.
 *
 * ── THE OPT-OUT FILE (`.claude/adapters.project.json`, dev-owned) ───────────────────────
 *
 * Shape — one key, runtime names from the table below:
 *
 *     { "disabled": ["cursor", "hermes"] }     // valid: codex · cursor · copilot · hermes
 *
 * It answers the one question the ownership marker cannot: an output that is NOT THERE has
 * no marker to read, so without a declaration "absent" would mean "absent until the next
 * commit" — the hook would recreate it forever. A derivative that does not use Cursor
 * declares it once and the file stays gone.
 *
 * `*.project.*` is the kit's dev-owned pattern (`.husky/pre-commit.project`,
 * `.claude/policy/quality-gates.project.json`): the file is excluded from BOTH distribution
 * profiles, so `factory update` neither ships it nor overwrites it.
 *
 * An opt-out governs GENERATION, never deletion: an output that is already on disk is left
 * exactly as it is (and reported), because deleting a committed file behind the dev's back
 * is not what declaring a preference asked for.
 *
 * ABSENT is the normal case and prints nothing. A file that IS there but is corrupt (bad
 * JSON, or a shape that is not `{ disabled: string[] }`) FAILS with exit 1: silently
 * ignoring it would generate the very outputs the dev declared away, which is the opposite
 * of what the file says. An unknown runtime name is only a warning — it opts nothing out,
 * but it is a typo in a preference file, not a corrupt input.
 *
 * ── WHAT `.hermes.md` OMITS ─────────────────────────────────────────────────────────────
 *
 * "Orchestration vocabulary" = the two `CLAUDE.md` sections `## Convenciones de nomenclatura
 * de skills` and `## Convenciones de nomenclatura de agents`. They describe the prefixes of
 * the kit's own pipeline (`tk-*`/`kb-*`/`sk-*`/`fx-*`, `dsc-*`/`bkl-*`/`imp-*`…), which is
 * vocabulary for agents that run the pipeline. The other three outputs keep them.
 *
 * Stays plain-node `.mjs` ON PURPOSE (like the mould, unlike the `generate-*.ts` family):
 * the pre-commit hook invokes it BY PATH on heterogeneous derivatives, and `tsx` is a
 * dev-owned devDependency the kit cannot assume exists there.
 */

import {
  readFileSync,
  writeFileSync,
  existsSync,
  mkdirSync,
  renameSync,
  unlinkSync,
} from 'node:fs';
import { basename, dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

import { isMainModule } from './lib/is-main-module.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

const ENTRY = 'CLAUDE.md';
const INDEX = '.claude/rules/INDEX.md';
/** Only files under this prefix are projected — see the boundary note in the header. */
const PROJECTED_PREFIX = '.claude/rules/';
/** Excluded by name while walking the graph, never by sniffing its content. */
const EXCLUDED_BASENAME = 'CC.md';

const GENERATOR = 'scripts/tools/generate-agent-adapters.mjs';
const MARKER = `@generated by ${GENERATOR} — do not edit by hand`;
/** How many leading lines `hasGeneratedMarker` scans (the .mdc frontmatter pushes it down). */
const MARKER_SCAN_LINES = 20;

/** The two CLAUDE.md sections `.hermes.md` leaves out — matched by exact heading line. */
const ORCHESTRATION_VOCABULARY = [
  '## Convenciones de nomenclatura de skills',
  '## Convenciones de nomenclatura de agents',
];

const MDC_FRONTMATTER = [
  '---',
  'description: TimeKast Factory — rules del kit (archivo generado, no editar a mano)',
  'alwaysApply: true',
  '---',
].join('\n');

/** Dev-owned opt-out (see the header). Absent = normal; corrupt = fail-closed. */
const OPT_OUT_FILE = '.claude/adapters.project.json';

/**
 * The four outputs are fixed by the plan — filenames are each tool's convention, not a
 * choice. `key` is the name the opt-out file uses: the runtime, not the path, because the
 * dev declares "I don't use Cursor", not "I don't want .cursor/rules/timekast.mdc".
 */
const TARGETS = [
  { key: 'codex', rel: 'AGENTS.md', runtime: 'Codex' },
  {
    key: 'cursor',
    rel: '.cursor/rules/timekast.mdc',
    runtime: 'Cursor',
    frontmatter: MDC_FRONTMATTER,
  },
  { key: 'copilot', rel: '.github/copilot-instructions.md', runtime: 'GitHub Copilot' },
  { key: 'hermes', rel: '.hermes.md', runtime: 'Hermes', omitSections: ORCHESTRATION_VOCABULARY },
];

/** A whole-line `@path.md` memory import, and nothing else on the line. */
const IMPORT_LINE = /^@([^\s]+\.md)$/;

// ── helpers ─────────────────────────────────────────────────────────────────────────────

/**
 * True when `content` was produced by THIS generator. PROJ-004's ownership guard: an
 * adapter without the marker belongs to the derivative and must never be overwritten.
 *
 * @param {unknown} content
 * @returns {boolean}
 */
export function hasGeneratedMarker(content) {
  if (typeof content !== 'string') return false;
  return content.split('\n', MARKER_SCAN_LINES).some((line) => line.includes(MARKER));
}

function fail(msg) {
  console.error(`✖ generate:adapters — ${msg}`);
  process.exit(1);
}

function note(msg) {
  console.log(`↷ generate:adapters — ${msg}`);
}

/**
 * Read the dev-owned opt-out. Returns the set of runtime keys that must NOT be generated.
 *
 * @returns {Set<string>}
 */
function readOptOut() {
  const abs = join(ROOT, OPT_OUT_FILE);
  if (!existsSync(abs)) return new Set(); // the normal case — no file, no message

  let parsed;
  try {
    parsed = JSON.parse(readFileSync(abs, 'utf8'));
  } catch (err) {
    fail(`${OPT_OUT_FILE} is not valid JSON: ${err.message}`);
  }

  const known = TARGETS.map((t) => t.key);
  const shape = `expected { "disabled": [${known.map((k) => `"${k}"`).join(' | ')}] }`;
  if (parsed === null || typeof parsed !== 'object' || Array.isArray(parsed)) {
    fail(`${OPT_OUT_FILE} must be a JSON object — ${shape}`);
  }
  const disabled = parsed.disabled ?? [];
  if (!Array.isArray(disabled) || disabled.some((k) => typeof k !== 'string')) {
    fail(`${OPT_OUT_FILE}: "disabled" must be an array of strings — ${shape}`);
  }

  for (const key of disabled) {
    if (!known.includes(key)) {
      note(`${OPT_OUT_FILE}: unknown runtime "${key}" (known: ${known.join(', ')}); ignoring it`);
    }
  }
  return new Set(disabled);
}

/**
 * The projection system not being initialized in this repo is a VALID state (a derivative
 * that predates the INDEX runs this via the shipped hook) — exit 0, never a crash.
 */
function skipUninitialized(reason) {
  console.log(
    `✓ generate:adapters — ${reason}; skipping (an uninitialized projection graph is valid)`
  );
  process.exit(0);
}

/** Repo-relative, POSIX-separated path — the form the boundary check is applied to. */
function toRepoRel(abs) {
  return relative(ROOT, abs).split(sep).join('/');
}

/** Collapse runs of blank lines to one and trim the ends, so dropped lines leave no holes. */
function tidy(lines) {
  const out = [];
  for (const line of lines) {
    if (line.trim() === '' && out.length > 0 && out[out.length - 1].trim() === '') continue;
    out.push(line);
  }
  while (out.length && out[0].trim() === '') out.shift();
  while (out.length && out[out.length - 1].trim() === '') out.pop();
  return out;
}

/**
 * Split a file into its own prose and the specs it imports, in order.
 *
 * An import line never survives verbatim: `@path` is Claude Code memory syntax and means
 * nothing to the other runtimes. `replace` decides what takes its place — a projected
 * import leaves a pointer behind (otherwise `## Rules (auto-loaded)` would render as an
 * empty heading), an out-of-boundary one is dropped without a trace.
 */
function splitImports(content, replace = () => null) {
  const imports = [];
  const body = [];
  for (const line of content.split('\n')) {
    const match = line.trim().match(IMPORT_LINE);
    if (match) {
      imports.push(match[1]);
      const substitute = replace(match[1]);
      if (substitute !== null) body.push(substitute);
      continue;
    }
    body.push(line);
  }
  return { imports, body: tidy(body).join('\n') };
}

/**
 * Drop whole `## ` sections by exact heading line. A section runs until the next h1/h2
 * heading OR a horizontal rule — the rule matters because the last section of CLAUDE.md is
 * followed by `---` + the file footer, which must survive the omission.
 */
function dropSections(body, headings) {
  const out = [];
  let skipping = false;
  for (const line of body.split('\n')) {
    if (skipping) {
      if (/^#{1,2}\s/.test(line) || /^-{3,}\s*$/.test(line)) skipping = false;
      else continue;
    }
    if (headings.includes(line.trim())) {
      skipping = true;
      continue;
    }
    out.push(line);
  }
  return tidy(out).join('\n');
}

// ── graph ───────────────────────────────────────────────────────────────────────────────

/**
 * Walk the bounded import graph depth-first from CLAUDE.md.
 *
 * @returns {{ claudeBody: string, sections: {rel: string, body: string}[] }}
 */
function collectGraph() {
  const entryAbs = join(ROOT, ENTRY);
  if (!existsSync(entryAbs)) skipUninitialized(`no ${ENTRY} in this repo`);

  const projectedRel = (spec, containerAbs) => {
    if (spec.startsWith('~/')) return null;
    const rel = toRepoRel(resolve(dirname(containerAbs), spec));
    if (!rel.startsWith(PROJECTED_PREFIX)) return null;
    if (basename(rel) === EXCLUDED_BASENAME) return null;
    return rel;
  };

  /** What a projected `@import` line becomes in the output prose. */
  const pointer = (containerAbs) => (spec) => {
    const rel = projectedRel(spec, containerAbs);
    return rel === null
      ? null
      : `> _(Incluido al final de este archivo: \`${rel}\` y las rules que enlaza.)_`;
  };

  const entry = splitImports(readFileSync(entryAbs, 'utf8'), pointer(entryAbs));
  const sections = [];
  const visited = new Set();

  const walk = (specs, containerAbs) => {
    for (const spec of specs) {
      // boundary (on the RESOLVED path), CC.md by name, and home-relative specs: all out
      const rel = projectedRel(spec, containerAbs);
      if (rel === null) continue;
      if (visited.has(rel)) continue; // reached twice → projected once
      visited.add(rel);
      const abs = join(ROOT, rel);

      if (!existsSync(abs)) {
        skipUninitialized(`${rel} is referenced by the graph but not on disk`);
      }

      const file = splitImports(readFileSync(abs, 'utf8'), pointer(abs));
      if (rel !== INDEX) sections.push({ rel, body: file.body });
      walk(file.imports, abs);
    }
  };

  walk(entry.imports, entryAbs);
  // The real precondition: a graph that reaches no rule at all has nothing to project, and
  // emitting four adapters made of CLAUDE.md alone would claim a projection nobody wired.
  if (sections.length === 0) {
    skipUninitialized(`${ENTRY} reaches no rule under ${PROJECTED_PREFIX}`);
  }
  return { claudeBody: entry.body, sections };
}

// ── rendering ───────────────────────────────────────────────────────────────────────────

function header(target, sources) {
  return [
    '<!--',
    `  ${MARKER}.`,
    `  Runtime: ${target.runtime}. Regenerate with: node ${GENERATOR}`,
    `  Sources: ${sources.join(' · ')}`,
    '-->',
  ].join('\n');
}

function render(target, claudeBody, sections) {
  const sources = [ENTRY, ...sections.map((s) => s.rel)];
  const parts = [];
  if (target.frontmatter) parts.push(target.frontmatter);
  parts.push(header(target, sources));
  parts.push(target.omitSections ? dropSections(claudeBody, target.omitSections) : claudeBody);
  for (const section of sections) {
    parts.push('---');
    parts.push(`<!-- source: ${section.rel} -->`);
    parts.push(section.body);
  }
  return `${parts.join('\n\n')}\n`;
}

/**
 * A compact line-level preview of what `--check` found. Not a real diff algorithm on
 * purpose: its job is to point at WHICH lines moved and at the regenerate command, and a
 * naive scan stays readable for the append/edit shapes this generator actually produces.
 */
function diffPreview(expected, actual) {
  const want = expected.split('\n');
  const have = actual.split('\n');
  const max = Math.max(want.length, have.length);
  const out = [];
  let more = 0;
  for (let i = 0; i < max; i++) {
    if (want[i] === have[i]) continue;
    if (out.length >= 12) {
      more++;
      continue;
    }
    if (have[i] !== undefined) out.push(`    - ${i + 1}: ${truncate(have[i])}`);
    if (want[i] !== undefined) out.push(`    + ${i + 1}: ${truncate(want[i])}`);
  }
  if (more > 0) out.push(`    … ${more} more differing line(s)`);
  return out.join('\n');
}

function truncate(line) {
  return line.length > 110 ? `${line.slice(0, 107)}…` : line;
}

// ── writing ─────────────────────────────────────────────────────────────────────────────

/** Write via temp + rename: a failed write never leaves a half-written adapter behind. */
function writeAtomic(abs, content) {
  const tmp = `${abs}.tmp-${process.pid}`;
  try {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(tmp, content);
    renameSync(tmp, abs);
  } catch (err) {
    try {
      unlinkSync(tmp);
    } catch {
      /* nothing to clean up */
    }
    fail(`could not write ${toRepoRel(abs)}: ${err.message}`);
  }
}

// ── main ────────────────────────────────────────────────────────────────────────────────

/**
 * Decide, per output, whether this generator owns it at all. Two things can take an output
 * out of the generator's hands before any content is compared, and both are reported:
 *
 *   · `optedOut` — the dev declared the runtime away in `.claude/adapters.project.json`.
 *   · `foreign`  — the file is on disk WITHOUT the generated marker, so it is the
 *                  derivative's own file (PROJ-004's ownership guard).
 *
 * Neither is drift and neither is an error: `--check` ignores both, and write mode leaves
 * both alone. `stale` is what is left — the outputs this generator actually owns.
 */
function plan(claudeBody, sections, disabled) {
  return TARGETS.map((target) => {
    const abs = join(ROOT, target.rel);
    const actual = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
    if (disabled.has(target.key)) return { target, abs, actual, skip: 'opted-out' };
    if (actual !== null && !hasGeneratedMarker(actual)) {
      return { target, abs, actual, skip: 'foreign' };
    }
    const expected = render(target, claudeBody, sections);
    return { target, abs, actual, expected, skip: null, inSync: actual === expected };
  });
}

/** One line per output the generator does not own, so a skip is never silent. */
function reportSkips(planned) {
  for (const p of planned) {
    if (p.skip === 'opted-out') {
      note(
        p.actual === null
          ? `${p.target.rel}: opted out in ${OPT_OUT_FILE}; not generated`
          : `${p.target.rel}: opted out in ${OPT_OUT_FILE}; left on disk as is (an opt-out stops generation, it does not delete)`
      );
    }
    if (p.skip === 'foreign') {
      note(
        `${p.target.rel}: no generated marker — this file belongs to the project; not overwritten`
      );
    }
  }
}

function main() {
  const check = process.argv.includes('--check');
  const disabled = readOptOut();
  const { claudeBody, sections } = collectGraph();

  const planned = plan(claudeBody, sections, disabled);
  reportSkips(planned);

  // Counts are over the OWNED outputs, never over all four: reporting "4 in sync" while
  // one of them is opted out or project-owned would claim a sync nobody checked.
  const managed = planned.filter((p) => p.skip === null);
  const stale = managed.filter((p) => !p.inSync);

  if (check) {
    if (stale.length === 0) {
      console.log(`✓ generate:adapters — ${managed.length} adapters in sync`);
      process.exit(0);
    }
    const detail = stale
      .map((p) => {
        if (p.actual === null) return `  ${p.target.rel}: missing (would be created)`;
        return `  ${p.target.rel}: out of sync\n${diffPreview(p.expected, p.actual)}`;
      })
      .join('\n');
    fail(
      `${stale.length} of ${managed.length} adapters are out of sync with ${ENTRY} + the rules graph.\n` +
        `${detail}\n` +
        `  → run \`node ${GENERATOR}\``
    );
  }

  if (stale.length === 0) {
    console.log(`✓ generate:adapters — ${managed.length} adapters already up to date`);
    process.exit(0);
  }

  for (const p of stale) writeAtomic(p.abs, p.expected);
  console.log(
    `✓ generate:adapters — wrote ${stale.length} of ${managed.length} adapters (${stale
      .map((p) => p.target.rel)
      .join(', ')})`
  );
}

if (isMainModule(import.meta.url, process.argv[1])) main();
