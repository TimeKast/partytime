#!/usr/bin/env node
/**
 * Generate the `-dev` PWA icon variants for env-aware install identity.
 *
 * Reads the shipped base icons under `public/pwa/` (icon-192.png, icon-256.png,
 * icon-384.png, icon-512.png, apple-touch-icon.png, maskable-512.png) and writes
 * a variant of each — same filename — into the `public/pwa/dev/` subfolder,
 * overlaying a visible "DEV" ribbon with `sharp`'s `composite`. This lets a PWA
 * installed from a non-production environment (develop / staging / preview) be
 * told apart at a glance from the production install — `src/app/manifest.ts` +
 * `src/app/layout.tsx` point at the `dev/` assets when `NEXT_PUBLIC_APP_ENV !==
 * 'production'`.
 *
 * The `dev/` subfolder is gitignored and regenerated by the prebuild: the
 * variants are derived outputs (never hand-edited), so they stay out of git and
 * never mix with the source icons a derived project replaces with its own brand.
 *
 * Idempotent: re-running with the same base inputs produces byte-identical
 * outputs (the ribbon SVG is deterministic). Wired into the existing `prebuild`
 * after `generate:email-logo`.
 *
 * Usage:
 *   node scripts/tools/generate-pwa-icons.mjs        # write -dev variants
 *   pnpm generate:pwa-icons                          # same, via package.json
 *
 * Errors loudly (exit 1) if a required base icon is missing, instead of writing
 * a corrupt or partial asset. `maskable-512.png` gets a `-dev` variant too, but
 * with its ribbon pulled toward the center (smaller `offsetFactor`) so the band
 * and "DEV" label clear the maskable safe-zone (central 80% circle) instead of
 * being cropped at the corner by Android's adaptive mask.
 *
 * Testable shape: the pure helpers (`buildRibbonSvg`, `iconTargets`,
 * `devVariantPath`) and the injectable orchestrator (`generatePwaIcons`) are
 * exported. `main()` runs only when the file is invoked directly.
 */

import { existsSync, mkdirSync } from 'fs';
import { join, basename, resolve } from 'path';
import { pathToFileURL } from 'url';

// ─────────────────────────────────────────────────────────────────────────────
// Config
// ─────────────────────────────────────────────────────────────────────────────

const PWA_DIR = 'public/pwa';

// Generated `-dev` variants live in this subfolder of PWA_DIR (gitignored,
// regenerated by the prebuild) so they never mix with the source base icons.
const DEV_DIR = 'dev';

// Ribbon placement along the corner diagonal. The square icons use a corner
// ribbon; the maskable variant pulls it toward the center so the band + label
// clear the maskable safe-zone (central 80% circle, radius 0.4). The outer band
// edge sits at radius ≈ offsetFactor/√2 of the icon, so 0.54 keeps it at ~0.38.
const DEFAULT_OFFSET_FACTOR = 0.62;
const MASKABLE_OFFSET_FACTOR = 0.54;

/**
 * Base icons that MUST exist and MUST get a `-dev` variant. The number is the
 * canvas dimension (square) used to size the ribbon proportionally; the
 * apple-touch-icon is 180×180 by kit convention (layout.tsx declares 180).
 * `offsetFactor` defaults to the corner-ribbon depth; the maskable base overrides
 * it to pull the ribbon inside the adaptive safe-zone.
 */
const ICON_BASES = [
  { name: 'icon-192.png', size: 192 },
  { name: 'icon-256.png', size: 256 },
  { name: 'icon-384.png', size: 384 },
  { name: 'icon-512.png', size: 512 },
  { name: 'apple-touch-icon.png', size: 180 },
  { name: 'maskable-512.png', size: 512, offsetFactor: MASKABLE_OFFSET_FACTOR },
];

// Ribbon colors — kept local to the asset generator (visual marker, not app
// theme). These are not app UI tokens, so they live with the script that draws
// the overlay rather than in src/config/branding.ts.
const RIBBON_FILL = '#dc2626'; // red-600 — high-contrast "this is not prod" marker
const RIBBON_TEXT = '#ffffff';

// ─────────────────────────────────────────────────────────────────────────────
// Pure helpers (exported for unit tests)
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Map a base icon filename to its dev-variant path, relative to PWA_DIR. The
 * variant keeps the same filename inside the `dev/` subfolder (the folder denotes
 * the env, so no `-dev` suffix). `icon-192.png` → `dev/icon-192.png`.
 */
export function devVariantPath(baseName) {
  return `${DEV_DIR}/${baseName}`;
}

/**
 * Build a deterministic "DEV" ribbon as an SVG buffer, sized proportionally to
 * the target icon. Diagonal banner crossing the top-right corner; a smaller
 * `offsetFactor` slides it inward along the corner diagonal (kept symmetric) so
 * the maskable variant lands inside the safe-zone. Deterministic input →
 * idempotent output.
 */
export function buildRibbonSvg(size, { offsetFactor = DEFAULT_OFFSET_FACTOR } = {}) {
  // Ribbon band height scales with the icon; font sits centered in the band. The
  // band is kept narrow (less invasive) with the label at a slightly higher
  // band-ratio so it stays legible. Band width does not affect the maskable
  // safe-zone fit — the outer edge stays at offsetFactor/√2 regardless.
  const band = Math.max(Math.round(size * 0.205), 24);
  const fontSize = Math.max(Math.round(band * 0.52), 10);
  // The band is drawn rotated 45° and shifted along the corner diagonal.
  const offset = size * offsetFactor;
  // Center the label on the VISIBLE slice of the band (the part inside the
  // square), not on the full band's geometric midpoint. The visible center along
  // the band axis is (size - offset)/√2; with x=0 the label sat pulled toward the
  // top-left of the band.
  const textX = (size - offset) / Math.SQRT2;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
  <g transform="translate(${offset} 0) rotate(45)">
    <rect x="${-size}" y="0" width="${size * 2}" height="${band}" fill="${RIBBON_FILL}"/>
    <text x="${textX}" y="${band / 2}" fill="${RIBBON_TEXT}" font-family="Arial, sans-serif" font-size="${fontSize}" font-weight="bold" text-anchor="middle" dominant-baseline="central" letter-spacing="${Math.round(fontSize * 0.15)}">DEV</text>
  </g>
</svg>`;
  return Buffer.from(svg);
}

/**
 * Resolve the absolute input/output/ribbon spec for every required icon base,
 * relative to a repo root. `offsetFactor` falls back to the corner-ribbon depth.
 */
export function iconTargets(root = process.cwd()) {
  return ICON_BASES.map(({ name, size, offsetFactor }) => ({
    name,
    size,
    offsetFactor: offsetFactor ?? DEFAULT_OFFSET_FACTOR,
    input: resolve(root, PWA_DIR, name),
    output: resolve(root, PWA_DIR, devVariantPath(name)),
  }));
}

// ─────────────────────────────────────────────────────────────────────────────
// Orchestrator (injectable deps for tests)
// ─────────────────────────────────────────────────────────────────────────────

/**
 * @typedef {Object} GenerateDeps
 * @property {(input: string) => { composite: (layers: any[]) => { toFile: (out: string) => Promise<any> } }} sharp
 * @property {(path: string) => boolean} [fileExists]
 * @property {(dir: string) => void} [ensureDir]
 * @property {(msg: string) => void} [log]
 */

/**
 * Generate the `-dev` variant for every required base icon by compositing the
 * ribbon over the base, writing into the `dev/` subfolder. Throws a descriptive
 * error (and writes nothing) if a required base icon is missing.
 *
 * @param {GenerateDeps} deps
 * @param {{ root?: string }} [opts]
 * @returns {Promise<{ written: string[] }>}
 */
export async function generatePwaIcons(deps, opts = {}) {
  const root = opts.root ?? process.cwd();
  const fileExists = deps.fileExists ?? existsSync;
  const ensureDir = deps.ensureDir ?? ((dir) => mkdirSync(dir, { recursive: true }));
  const log = deps.log ?? ((m) => console.log(m));

  if (typeof deps.sharp !== 'function') {
    throw new Error('generate-pwa-icons: a `sharp` dependency is required.');
  }

  const targets = iconTargets(root);

  // Fail fast — verify every required base exists BEFORE writing anything, so a
  // missing input never leaves a partial set of variants behind.
  const missing = targets.filter((t) => !fileExists(t.input)).map((t) => t.name);
  if (missing.length > 0) {
    throw new Error(
      `generate-pwa-icons: missing base icon(s) in ${PWA_DIR}/: ${missing.join(', ')}. ` +
        `Cannot generate -dev variants without the base assets.`
    );
  }

  // The dev/ subfolder is gitignored, so it may not exist on a fresh checkout.
  ensureDir(resolve(root, PWA_DIR, DEV_DIR));

  const written = [];
  for (const target of targets) {
    const ribbon = buildRibbonSvg(target.size, { offsetFactor: target.offsetFactor });
    await deps
      .sharp(target.input)
      .composite([{ input: ribbon, gravity: 'northeast' }])
      .toFile(target.output);
    written.push(target.output);
    log(`✓ ${basename(target.output)}`);
  }

  return { written };
}

// ─────────────────────────────────────────────────────────────────────────────
// CLI entrypoint (runs only when invoked directly)
// ─────────────────────────────────────────────────────────────────────────────

async function main() {
  const cwd = process.cwd();
  const pwaDir = join(cwd, PWA_DIR);

  if (!existsSync(pwaDir)) {
    // Derived non-Next project without the kit's PWA assets: nothing to do.
    console.log(`generate-pwa-icons: ${PWA_DIR}/ not found — skipping (no-op).`);
    return;
  }

  // Lazy-import sharp so the module stays importable in tests that mock it.
  const sharp = (await import('sharp')).default;
  const { written } = await generatePwaIcons({ sharp });
  console.log(
    `✓ generate-pwa-icons — ${written.length} -dev variant(s) written to ${PWA_DIR}/${DEV_DIR}/`
  );
}

const invokedDirectly = (() => {
  const entry = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : '';
  return entry === import.meta.url;
})();

if (invokedDirectly) {
  main().catch((err) => {
    console.error('❌ generate-pwa-icons failed:', err instanceof Error ? err.message : err);
    process.exit(1);
  });
}
